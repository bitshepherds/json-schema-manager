package main

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestReportsRule(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		out  string
		rule string
		want bool
	}{
		{
			name: "plain output names the rule",
			out:  "Error was generated by the struct rule.\n",
			rule: "the struct rule",
			want: true,
		},
		{
			// Redocly colours the rule name when CI and GITHUB_ACTIONS are set, on Windows, or at a terminal.
			name: "coloured output names the rule",
			out:  "Error was generated by the \x1b[34mstruct\x1b[39m rule.\n",
			rule: "the struct rule",
			want: true,
		},
		{
			name: "coloured output with a hyperlink names the rule",
			out:  "\x1b]8;;https://redocly.com\x07the \x1b[1;34mno-unresolved-refs\x1b[0m rule\x1b]8;;\x07",
			rule: "the no-unresolved-refs rule",
			want: true,
		},
		{
			name: "coloured output names another rule",
			out:  "Warning was generated by the \x1b[34msecurity-defined\x1b[39m rule.\n",
			rule: "the struct rule",
			want: false,
		},
		{
			name: "a bare word is not the rule",
			out:  "TypeError: cannot read struct of undefined\n",
			rule: "the struct rule",
			want: false,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			assert.Equal(t, tt.want, reportsRule(tt.out, tt.rule))
		})
	}
}
